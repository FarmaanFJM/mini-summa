import { launchApp } from '../helpers/app.ts';
import { createProject, startSession } from '../helpers/core.ts';
import { finishTask } from '../helpers/flow.ts';
import { scenario } from '../helpers/scenario.ts';
import { conversationUrl, uuidOf } from '../helpers/standin.ts';
import { claudeTabs, projectRow, selectProject } from '../helpers/ui.ts';

scenario('[ZZ] debug restart pane', async () => {
  const h = await launchApp();
  const alpha = await createProject(h, 'Alpha', { conversations: [conversationUrl(uuidOf('a1'))] });
  const beta = await createProject(h, 'Beta', { conversations: [conversationUrl(uuidOf('b'))] });
  const build = await startSession(h, alpha.project.id, { name: 'build' });
  const idle = await startSession(h, alpha.project.id);
  const betaSession = await startSession(h, beta.project.id);
  await finishTask(h, { project: alpha.project, session: build }, 'Alpha one');
  await finishTask(h, { project: beta.project, session: betaSession }, 'Beta one');
  console.log('BUILD', build.key, 'IDLE', idle.key);
  await h.quit();
  const h2 = await launchApp({ sandbox: h.sandbox, standIn: h.standIn });
  await projectRow(h2.page, 'Alpha').waitFor();
  console.log('HEADING-AFTER-RESTART', await h2.page.getByRole('heading', { level: 1 }).first().innerText());
  await selectProject(h2.page, 'Alpha');
  await new Promise((r) => setTimeout(r, 1500));
  const region = h2.page.getByRole('region', { name: 'Claude', exact: true });
  console.log('CLAUDE-REGION-TEXT>>>' + (await region.innerText()) + '<<<');
  const tabs = claudeTabs(h2.page);
  const n = await tabs.count();
  for (let i = 0; i < n; i += 1) console.log('TAB', i, await tabs.nth(i).getAttribute('aria-label'), '|', await tabs.nth(i).innerText(), '| selected=', await tabs.nth(i).getAttribute('aria-selected'));
  console.log('LS', await h2.page.evaluate(() => JSON.stringify(Object.fromEntries(Object.entries(localStorage)))));
});
