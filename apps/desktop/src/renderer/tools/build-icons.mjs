// Generates src/ui/icons.generated.ts from the vendored Summa-UI icon catalog.
//
//   node apps/desktop/src/renderer/tools/build-icons.mjs
//
// The renderer may only use catalogued icons (Lucide subset, stroke 1.75, 24px grid). Emitting the shapes as data keeps
// `IconName` a closed union, so an icon outside the catalog is a compile error instead of a review comment.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const bundle = join(here, '../../../../../third_party/summa-ui-guidance/icons');
const catalog = JSON.parse(readFileSync(join(bundle, 'catalog.json'), 'utf8'));

const ATTR = /([a-zA-Z][a-zA-Z0-9:-]*)="([^"]*)"/g; // names such as x1 and y2 contain digits
const CHILD = /<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g;

function parseShapes(svg, name) {
  const inner = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>'));
  const shapes = [];
  for (const m of inner.matchAll(CHILD)) {
    const attrs = {};
    for (const a of m[2].matchAll(ATTR)) attrs[a[1]] = a[2];
    shapes.push([m[1], attrs]);
  }
  if (shapes.length === 0) throw new Error(`No shapes parsed for icon "${name}"`);
  return shapes;
}

const lines = [
  '// GENERATED by src/renderer/tools/build-icons.mjs from third_party/summa-ui-guidance/icons. Do not edit by hand.',
  `// Lucide ${catalog.source.version} (${catalog.source.license}), ${catalog.icons.length} icons, stroke ${catalog.stroke.width}.`,
  "export type IconShape = readonly [tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse', attrs: Readonly<Record<string, string>>];",
  '',
  'export const ICONS = {',
];
for (const icon of catalog.icons) {
  const svg = readFileSync(join(bundle, 'svg', `${icon.name}.svg`), 'utf8');
  lines.push(`  ${JSON.stringify(icon.name)}: ${JSON.stringify(parseShapes(svg, icon.name))},`);
}
lines.push('} as const satisfies Record<string, readonly IconShape[]>;', '', 'export type IconName = keyof typeof ICONS;', '');

const out = join(here, '../src/ui/icons.generated.ts');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${catalog.icons.length} icons to ${out}`);
